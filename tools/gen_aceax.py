def q(text: str) -> str:
    return '"' + str(text).replace('"', '""') + '"'


def render_common(ov: dict) -> str:
    out = [BANNER, "\n"]

    out.append("// Extra finishes merged into the palette aceax_gearinfo already provides.\n")
    out.append("// Values such as BLK/TAN/GRN/OD/BLU/FDE are reused from there and\n")
    out.append("// deliberately not repeated.\n")
    out.append("class CamoBase\n{\n")
    for name, meta in ov["camo_values"].items():
        out.append(f"    class {name}\n    {{\n")
        out.append(f"        label = {q(meta['label'])};\n")
        if meta.get("description"):
            out.append(f"        description = {q(meta['description'])};\n")
        if meta.get("color"):
            r, g, b = meta["color"]
            out.append(f'        image = "#(rgb,8,8,3)color({r},{g},{b},1)";\n')
        out.append("    };\n")
    out.append("};\n\n")

    out.append("// Shared option definitions. Models inherit these so labels and value\n")
    out.append("// descriptions are written once, the way compat_rhs does with rhs_attachsys.\n")
    for axis, meta in ov["option_bases"].items():
        out.append(f"class {meta['class']}\n{{\n")
        out.append(f"    label = {q(meta['label'])};\n")
        out.append("    changeingame = 0;\n")
        out.append("    values[] = {};\n")
        for value, vmeta in meta["values"].items():
            out.append(f"    class {value}\n    {{\n")
            out.append(f"        label = {q(vmeta['label'])};\n")
            if vmeta.get("description"):
                out.append(f"        description = {q(vmeta['description'])};\n")
            out.append("    };\n")
        out.append("};\n\n")

    return "".join(out)


def render_model(model: Model, ov: dict) -> str:
    out = [BANNER, f"class {model.name}\n{{\n"]
    out.append(f"    label = {q(model.label)};\n")
    out.append(f"    author = {q(model.author)};\n")
    out.append("    options[] = {" + ", ".join(q(a) for a in model.axes) + "};\n")
    for axis in model.axes:
        base = ov["options"][axis].get("base")
        header = f"    class {axis} : {base}" if base else f"    class {axis}"
        out.append(header + "\n    {\n")
        out.append(
            "        values[] = {"
            + ", ".join(q(v) for v in model.axis_values[axis])
            + "};\n"
        )
        if model.sparse:
            out.append("        alwaysSelectable = 1;\n")
        out.append("    };\n")
    out.append("};\n")
    return "".join(out)


def render_infos(model: Model) -> str:
    out = [BANNER]
    for m in model.members:
        out.append(f"class {m.item.name}\n{{\n")
        out.append(f"    model = {q(model.name)};\n")
        for axis in model.axes:
            out.append(f"    {axis} = {q(m.values[axis])};\n")
        out.append("};\n")
    return "".join(out)


def render_index(models: list[Model], tree: str) -> str:
    """One `class <ConfigRoot>` block per root that has models.

    Backpacks live in CfgVehicles and facewear in CfgGlasses, so a gear compat
    emits up to three of these. The same model class name may appear under two
    roots without clashing -- they are different config paths, and ACEAX always
    looks a model up under the root of the item that referenced it.
    """
    out = [BANNER, f"class {tree}\n{{\n"]
    if tree == "XtdGearModels":
        out.append('    #include "XtdGearModels_Common.hpp"\n')
    for root in sorted({m.config_root for m in models}):
        in_root = [m for m in models if m.config_root == root]
        out.append(f"    class {root}\n    {{\n")
        for pack in sorted({m.pack for m in in_root}):
            out.append(f"        // {pack}\n")
            for model in [m for m in in_root if m.pack == pack]:
                out.append(f'        #include "{tree}\\{pack}\\{root}\\{model.name}.hpp"\n')
        out.append("    };\n")
    out.append("};\n")
    return "".join(out)


def render_config_cpp() -> str:
    mod = modinfo.load()
    return f"""class CfgPatches
{{
    class {mod.patch_class}
    {{
        name = {q(mod.name)};
        units[] = {{}};
        weapons[] = {{}};
        requiredVersion = "1.0";
        // Deliberately only aceax_gearinfo: listing the {mod.source_name} addons here
        // would stop the mod loading without it. XtdGearInfos references the source
        // classes by name, so nothing breaks when they are absent.
        requiredAddons[] = {{"aceax_gearinfo"}};
        author = {q(mod.author)};
        version = {q(mod.version)};
    }};
}};

#include "XtdGearModels.hpp"

#include "XtdGearInfos.hpp"
"""


def write(path: Path, text: str, written: set[Path]) -> bool:
    written.add(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    old = path.read_text(encoding="utf-8") if path.is_file() else None
    if old == text:
        return False
    path.write_text(text, encoding="utf-8", newline="\n")
    return True


def emit(models: list[Model], ov: dict) -> tuple[int, int]:
    written: set[Path] = set()
    changed = 0

    changed += write(ADDON / "config.cpp", render_config_cpp(), written)
    changed += write(ADDON / "XtdGearModels_Common.hpp", render_common(ov), written)
    changed += write(ADDON / "XtdGearModels.hpp", render_index(models, "XtdGearModels"), written)
    changed += write(ADDON / "XtdGearInfos.hpp", render_index(models, "XtdGearInfos"), written)

    for model in models:
        rel = Path(model.pack) / model.config_root / f"{model.name}.hpp"
        changed += write(ADDON / "XtdGearModels" / rel, render_model(model, ov), written)
        changed += write(ADDON / "XtdGearInfos" / rel, render_infos(model), written)

    # drop generated files that no longer correspond to a model
    removed = 0
    for tree in ("XtdGearModels", "XtdGearInfos"):
        for stale in sorted((ADDON / tree).rglob("*.hpp")):
            if stale not in written:
                stale.unlink()
                removed += 1
    return changed, removed


