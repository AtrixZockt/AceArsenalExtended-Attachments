def slug(text: str) -> str:
    out = re.sub(r"[^a-z0-9]+", "_", text.lower()).strip("_")
    return re.sub(r"_+", "_", out)


def collect(config: Config, ov: dict) -> tuple[list[Model], list[str], set[str]]:
    splitters: dict[str, str] = ov["splitters"]
    # Token matching is case-SENSITIVE, and deliberately so: NIArms distinguishes
    # "TAC" (a rail kit) from "Tac" (a receiver configuration) by capitalisation
    # alone. A mod that is merely inconsistent with itself -- MilGP writes both
    # "MC ARID" and "MC Arid" -- lists both spellings instead.
    #
    # str() guards against YAML 1.1 turning a bare YES/NO/ON/OFF value into a bool
    tokens = {k: (a, str(v)) for k, (a, v) in ov["tokens"].items()}
    suffixes = {k: (a, str(v)) for k, (a, v) in ov["class_suffixes"].items()}
    # Mirror of class_suffixes for mods that put the discriminator at the front.
    # Tier One ships every accessory once per weapon platform -- 23 classes all
    # called "LA-5B" -- and only the class name says which is which:
    #   Tier1_10_LA5_Side, Tier1_416_LA5_Side, Tier1_MCX_LA5_Side, ...
    prefixes = {k: (a, str(v)) for k, (a, v) in (ov.get("class_prefixes") or {}).items()}
    per_item: dict[str, dict] = {k.lower(): v for k, v in (ov.get("weapons") or {}).items()}
    opts: dict[str, dict] = ov["options"]

    # When a marker holds several values they may describe different PARTS of one
    # item rather than alternatives -- a uniform's top and its trousers. Where that
    # is so, the Nth mapped token is moved onto the Nth axis listed here, whatever
    # axis the token table gave it. Splitter tokens are not counted.
    positional = [str(a) for a in (ov.get("positional_axes") or [])]

    unknown: set[str] = set()
    grouped: dict[tuple[str, str], list[Member]] = collections.defaultdict(list)
    forced_pack: dict[tuple[str, str], str] = {}

    bases: dict[str, dict] = ov.get("bases") or {}

    # Names built by composition -- "Micro T-2/Leap/G33/LT 5/8". Absent for most
    # mods, in which case decompose_display_name is exactly parse_display_name.
    # Note the `bases:` lookup below is keyed on the DECOMPOSED base, so a rule
    # there matches the stem rather than every composition of it.
    compose: dict = ov.get("compose") or {}

    # Display-name mirror of class_prefixes, for mods that write the discriminator
    # on the FRONT of the name rather than in a "(...)" marker. VSM names every
    # vest "[VSM] <camo> <model> (<role>)", so one vest arrives under fifteen base
    # names. Longest first: "Multicam Arid" has to beat "Multicam".
    #
    # `keep` is the constant tag that survives at the front of the base -- VSM
    # prefixes everything with "[VSM] " and that is worth keeping in the arsenal,
    # so the match is made after it and it is put back.
    name_prefixes = sorted(
        ((str(k), (str(a), str(v))) for k, (a, v) in (ov.get("name_prefixes") or {}).items()),
        key=lambda kv: -len(kv[0]),
    )
    name_prefix_keep = str(ov.get("name_prefix_keep") or "")

    for item in config.arsenal_items():
        base, toks, parts = decompose_display_name(item.display_name, compose)
        values: dict[str, str] = {}
        extra: list[str] = []
        pack_override: str | None = None

        # Cut a leading discriminator out of the base name. Runs BEFORE the `bases:`
        # lookup so a rule there is written against the stem, not against every
        # prefixed spelling of it.
        if name_prefixes and base.startswith(name_prefix_keep):
            rest = base[len(name_prefix_keep):]
            for prefix, (axis, value) in name_prefixes:
                if rest.startswith(prefix):
                    values[axis] = value
                    base = name_prefix_keep + rest[len(prefix):]
                    break

        # The base table both renames a base and places it inside a family, by
        # supplying the option values that distinguish it there. Applied first so
        # display-name tokens and per-item overrides still win.
        # `as` and `pack` are reserved: everything else is an option value.
        rule = bases.get(base)
        if rule:
            for axis, value in rule.items():
                if axis == "as":
                    base = str(value)
                elif axis == "pack":
                    pack_override = str(value)
                else:
                    values[axis] = str(value)

        # Parts read out of the composed name. Same standing as display-name
        # tokens, which follow and may override them.
        values.update(parts)

        position = 0
        for tok in toks:
            if tok in splitters:
                extra.append(splitters[tok])
            elif tok in tokens:
                axis, value = tokens[tok]
                if position < len(positional):
                    axis = positional[position]
                position += 1
                values[axis] = value
            else:
                unknown.add(tok)

        lowered = item.name.lower()
        for prefix, (axis, value) in prefixes.items():
            if lowered.startswith(prefix.lower()):
                values[axis] = value
        for suffix, (axis, value) in suffixes.items():
            if lowered.endswith(suffix.lower()):
                values[axis] = value

        override = per_item.get(lowered) or {}
        for axis, value in override.items():
            values[axis] = str(value)

        # Keyed on (config root, label), not the pack: a mod and an add-on that
        # extends it name the same weapon the same way, and they belong in one
        # arsenal entry -- BWMod's "G36A1" and BWA3 Add's "G36A1 (White)" share the
        # base "G36A1" and should differ only by camo. The root has to stay in the
        # key because a model is emitted under exactly one of them, so a helmet and
        # a pair of goggles sharing a display name cannot be one model.
        label = base + "".join(f" ({e})" for e in extra)
        key = (item.config_root, label)
        grouped[key].append(Member(item, values))
        if pack_override:
            forced_pack[key] = pack_override

    models: list[Model] = []
    notes: list[str] = []
    pack_order = modinfo.load().pack_order

    for key in sorted(grouped):
        config_root, label = key
        members = grouped[key]
        if len(members) < 2:
            continue

        # the entry still lives in one pack, for its class name and file path:
        # whichever contributes most members, ties going to the earlier source
        counts = collections.Counter(m.item.pack for m in members)
        pack = forced_pack.get(key) or min(
            counts, key=lambda p: (-counts[p], pack_order.get(p, 1 << 30), p)
        )

        axes_used = {axis for m in members for axis in m.values}
        # fill defaults so every member has a value on every axis this group uses
        for m in members:
            for axis in axes_used:
                m.values.setdefault(axis, str(opts[axis]["default"]))

        # an axis everyone agrees on offers no choice
        axes = [a for a in ov["option_order"] if a in axes_used and len({m.values[a] for m in members}) > 1]
        for m in members:
            m.values = {a: m.values[a] for a in axes}
        if not axes:
            notes.append(f"[{pack}] {label}: {len(members)} items but no distinguishing option")
            continue

        model = Model(
            pack=pack,
            config_root=config_root,
            label=label,
            name=f"{modinfo.load().model_prefix}_{pack}_{slug(label)}",
            author=model_author(config, config_root, members[0].item.name),
            axes=axes,
            members=sorted(members, key=lambda m: m.item.name.lower()),
            member_packs=tuple(sorted(counts)),
        )
        model.axis_values = {a: order_values(a, members, ov) for a in axes}
        combos = 1
        for a in axes:
            combos *= len(model.axis_values[a])
        model.sparse = combos > len(members)
        models.append(model)

    # emitted order stays (root, pack, label), so the #include lists are stable
    models.sort(key=lambda m: (m.config_root, m.pack, m.label))

    # Entries are grouped by (config root, label) but the class name is built from
    # pack and label alone, so two entries that differ ONLY by root collide. VSM's
    # Peltor headset is both CfgWeapons headgear and CfgGlasses facewear under one
    # display name -- correctly two arsenal rows, but one class name, which Arma
    # rejects outright ("class defined multiple times").
    #
    # Renaming only the loser keeps every existing compat byte-identical: with no
    # collision this loop does nothing. Sorted order above makes which one loses
    # deterministic.
    seen: dict[str, Model] = {}
    for model in models:
        if model.name not in seen:
            seen[model.name] = model
            continue
        stem = f"{model.name}_{model.config_root.lower().removeprefix('cfg')}"
        candidate, n = stem, 2
        while candidate in seen:
            candidate, n = f"{stem}{n}", n + 1
        notes.append(
            f"[{model.pack}] {model.label}: name clashes with the {seen[model.name].config_root} "
            f"entry of the same name -- emitted as {candidate}"
        )
        model.name = candidate
        seen[candidate] = model

    return models, notes, unknown


def model_author(config: Config, config_root: str, item_name: str) -> str:
    """Credit the item's own author, falling back to the mod's name.

    `author` is frequently a stringtable key rather than a literal (BWmod points
    every weapon at $STR_BWA3_Author), so it goes through the same resolution as
    displayName. If the key is not in any dumped stringtable it stays a raw $STR_
    reference, which would show verbatim in the arsenal -- use the mod name then.
    """
    resolved = config.text(config.resolve(config_root, item_name, "author", "")).strip()
    if not resolved or resolved.startswith("$"):
        return modinfo.load().source_name
    return resolved


def order_values(axis: str, members: list[Member], ov: dict) -> list[str]:
    """Stable, meaningful value order: the declaration order in overrides.yml."""
    canonical = [str(ov["options"][axis]["default"])]
    # the shared option class lists its values in a deliberate order; follow it.
    # `camo` has no shared class (it inherits CamoBase), so fall back to the token
    # table, and to the base table for values only families introduce.
    base = ov["options"][axis].get("base")
    for meta in ov["option_bases"].values():
        if meta["class"] == base:
            canonical += [str(v) for v in meta["values"]]
    # the camo axes share one palette, so they share one ordering: a token mapped
    # to `camo` also fixes where that colour sits in the `pantscamo` dropdown,
    # which is the only way values moved there by positional_axes get an order
    camo_axes = [str(a) for a in (ov.get("camo_axes") or ["camo"])]
    wanted = set(camo_axes) if axis in camo_axes else {axis}
    canonical += [str(v) for _, (a, v) in ov["tokens"].items() if a in wanted]
    canonical += [str(v) for _, (a, v) in ov["class_suffixes"].items() if a == axis]
    canonical += [
        str(v) for _, (a, v) in (ov.get("class_prefixes") or {}).items() if a == axis
    ]
    used = {m.values[axis] for m in members}
    ordered = [v for v in dict.fromkeys(canonical) if v in used]
    # anything introduced only by a per-weapon override lands at the end
    ordered += sorted(used - set(ordered))
    return ordered


def find_unlabelled_camo(models: list[Model], ov: dict) -> list[str]:
    """Every camo value must resolve to a label somewhere.

    `camo` is a conventional option name, so aceax looks its values up in
    XtdGearModels >> Conventional >> camo, which inherits CamoBase -- the palette
    aceax_gearinfo ships plus whatever we merge into it. A value in neither shows
    up in the arsenal as its bare name.

    `pantscamo` is the other conventional option that inherits CamoBase, so a
    compat using it lists both in `camo_axes:`.
    """
    axes = [str(a) for a in (ov.get("camo_axes") or ["camo"])]
    known = {str(v) for v in ov["camo_values_from_aceax"]} | set(ov["camo_values"])
    missing = []
    for model in models:
        for axis in axes:
            for value in model.axis_values.get(axis, []):
                if value not in known:
                    missing.append(
                        f"{model.name}: {axis} value {value!r} has no CamoBase entry"
                    )
    return missing


def find_mixed_kinds(models: list[Model]) -> list[str]:
    """No model may span two arsenal tabs.

    ACEAX collapses a model's members within one panel, so a model holding both a
    primary and a handgun would hide one of them behind a dropdown on the wrong tab.
    hlc_smg_mp5k is the live case: rifle-rooted but type 2, so it belongs with the
    pistols and must not join the MP5 family.

    Grouping is keyed on the config root, which is not enough on its own: headgear,
    uniforms and vests are all CfgWeapons but three separate tabs, so a careless
    `bases:` line could merge a helmet with a plate carrier.
    """
    problems = []
    for model in models:
        kinds = {m.item.kind for m in model.members}
        if len(kinds) > 1:
            members = ", ".join(f"{m.item.name}({m.item.kind})" for m in model.members)
            problems.append(f"{model.name}: spans arsenal tabs {sorted(kinds)} -- {members}")
    return problems


def find_order_dependent(models: list[Model]) -> list[str]:
    """Models where selecting some variant relies on the weak-match fallback.

    See modconfig.unproven_variants: these usually work, but the config alone cannot
    prove it, so they are warnings rather than errors. Practically they mark the
    groupings that are riskiest to edit.
    """
    warnings = []
    for model in models:
        variations = {
            tuple(m.values[a] for a in model.axes): m.item.name for m in model.members
        }
        unproven = unproven_variants(
            variations, [model.axis_values[a] for a in model.axes]
        )
        if unproven:
            warnings.append(
                f"{model.name}: {len(unproven)} variant(s) reachable only via the "
                f"weak-match fallback -- {', '.join(unproven[:3])}"
                + (" ..." if len(unproven) > 3 else "")
            )
    return warnings


def find_duplicates(models: list[Model]) -> list[str]:
    problems = []
    for model in models:
        seen: dict[tuple[str, ...], str] = {}
        for m in model.members:
            key = tuple(m.values[a] for a in model.axes)
            if key in seen:
                problems.append(
                    f"{model.name}: {seen[key]} and {m.item.name} both map to "
                    + "+".join(key)
                )
            seen.setdefault(key, m.item.name)
    return problems


