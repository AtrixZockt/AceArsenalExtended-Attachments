def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="report only, write nothing")
    parser.add_argument("--list", action="store_true", help="print every model and its axes")
    args = parser.parse_args()

    ov = yaml.safe_load(OVERRIDES.read_text(encoding="utf-8"))
    config = Config.load()
    models, notes, unknown = collect(config, ov)

    items = config.arsenal_items()
    covered = sum(len(m.members) for m in models)
    print(
        f"{len(models)} models covering {covered}/{len(items)} arsenal-visible "
        f"{modinfo.load().source_names} items"
    )

    if args.list:
        kind_of = {i.name: i.kind for i in items}
        for m in models:
            axes = "  ".join(f"{a}[{'/'.join(m.axis_values[a])}]" for a in m.axes)
            kind = kind_of.get(m.members[0].item.name, "?")
            print(
                f"  {kind:<10}{m.pack:<16}{m.label:<34}{len(m.members):>3}  {axes}"
                + ("  SPARSE" if m.sparse else "")
            )

    if notes:
        print(f"\nskipped {len(notes)} group(s) with no distinguishing option:")
        for n in notes:
            print(f"  {n}")

    if unknown:
        print(f"\n{len(unknown)} unmapped displayName token(s) -- add to overrides.yml tokens:")
        for t in sorted(unknown):
            print(f"  {t!r}")

    # Usually vanilla classes the source mod only patches, whose displayName lives
    # on the vanilla class and so is not in the dump. Nothing to do about them --
    # they belong to a vanilla compat -- but they should not vanish silently.
    unnamed = config.unnamed_items()
    if unnamed:
        print(f"\n{len(unnamed)} item(s) skipped: no display name to group on")
        for i in unnamed[:10]:
            print(f"  {i.kind:<10} {i.name}")
        if len(unnamed) > 10:
            print(f"  ... and {len(unnamed) - 10} more")

    spanning = [m for m in models if len(m.member_packs) > 1]
    if spanning:
        print(f"\n{len(spanning)} entr(y/ies) merged across sources:")
        for m in spanning:
            print(f"  {m.label:<28} {'+'.join(m.member_packs)}  -> {m.name}")

    order_dependent = find_order_dependent(models)
    if order_dependent:
        print(f"\nwarning: {len(order_dependent)} model(s) depend on weak-match ordering:")
        for w in order_dependent:
            print(f"  {w}")

    problems = (
        find_duplicates(models)
        + find_mixed_kinds(models)
        + find_unlabelled_camo(models, ov)
    )
    if problems:
        print(f"\n{len(problems)} problem(s) aceax would reject or render badly:")
        for p in problems:
            print(f"  {p}")
        return 1

    if args.check:
        return 0

    changed, removed = emit(models, ov)
    print(f"\nwrote {changed} changed file(s), removed {removed} stale file(s)")
    return 0


