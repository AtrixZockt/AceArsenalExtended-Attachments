"""Generate the ACEAX XtdGearModels / XtdGearInfos trees for the mod in tools/mod.yml.

Reads the derapified configs in _dump/ (see dump_configs.py) plus the hand-written
judgement calls in tools/overrides.yml, and writes addons/main/. Idempotent: running
it twice produces no diff.

Usage:
    python tools/gen_aceax.py            # write the config
    python tools/gen_aceax.py --check    # report only, write nothing
"""

from __future__ import annotations

import argparse
import collections
import re
import sys
from dataclasses import dataclass, field
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent))

# These scripts print mod-authored display names, and Windows consoles default to
# a legacy codepage that cannot encode them -- RHS writes some Soviet loads in
# Cyrillic ("7Т3М"), which crashed `report.py --coverage` outright. Reconfigure
# stdout rather than stripping the names: the point of the report is to show what
# the mod actually calls things.
sys.stdout.reconfigure(encoding="utf-8", errors="replace")

import modinfo  # noqa: E402
from modconfig import Config, Item, decompose_display_name, unproven_variants  # noqa: E402

REPO = modinfo.REPO
ADDON = modinfo.ADDON
OVERRIDES = modinfo.OVERRIDES

BANNER = "// Generated by tools/gen_aceax.py -- do not edit by hand.\n"


@dataclass
class Member:
    item: Item
    values: dict[str, str]


@dataclass
class Model:
    pack: str
    config_root: str
    label: str
    name: str
    author: str
    axes: list[str] = field(default_factory=list)
    axis_values: dict[str, list[str]] = field(default_factory=dict)
    members: list[Member] = field(default_factory=list)
    sparse: bool = False
    member_packs: tuple[str, ...] = ()  # >1 means the entry spans sources


